// Rarity check against how famous things really are: English Wikipedia page views (last 60 days).
// An answer in a rare tier that's as looked-up as that prompt's common answers moves down to where it
// belongs (Frank's RedHot is not a One in a Vroomillion hot sauce). Answers are only ever made MORE
// common, never rarer. Writes public/vroomillion/js/data-rarity.js, which data.js applies.
//
//   node tools/rescale-rarity.mjs                 every prompt
//   node tools/rescale-rarity.mjs --only "Name a hot sauce"
import fs from "node:fs";
import { normalize } from "../public/vroomillion/js/logic.js";

const args = process.argv.slice(2);
const only = args.includes("--only") ? new Set(args[args.indexOf("--only") + 1].split(";")) : null;
const OUT = new URL("../public/vroomillion/js/data-rarity.js", import.meta.url);
const UA = "vroomillion-answer-builder/1.0 (trivia game rarity check)";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const PER_TIER = [25, 25, 70, 70, Infinity]; // how many answers per tier to look up (all of the rarest)

// page views are cached (VIEWS_CACHE=file) so the rules can be re-tuned without fetching again
const CACHE_FILE = process.env.VIEWS_CACHE || null;
const cache = CACHE_FILE && fs.existsSync(CACHE_FILE) ? new Map(Object.entries(JSON.parse(fs.readFileSync(CACHE_FILE, "utf8")))) : new Map();
const saveCache = () => { if (CACHE_FILE) fs.writeFileSync(CACHE_FILE, JSON.stringify(Object.fromEntries(cache))); };
const titleCase = (s) => s.replace(/(^|[\s(-])([a-z])/g, (m, a, b) => a + b.toUpperCase());
const firstUp = (s) => s.charAt(0).toUpperCase() + s.slice(1);

// views for up to 50 titles: Map(asked title -> views), following redirects; disambiguation pages count 0
async function views(titles) {
  const out = new Map();
  let cont = {};
  for (let page = 0; page < 6; page++) {
    const params = new URLSearchParams({ action: "query", format: "json", formatversion: "2", redirects: "1", prop: "pageviews|pageprops", pvipdays: "60", ppprop: "disambiguation", titles: titles.join("|"), ...cont });
    let j = null;
    for (let attempt = 0; attempt < 4 && !j; attempt++) {
      try {
        const res = await fetch("https://en.wikipedia.org/w/api.php?" + params, { headers: { "User-Agent": UA } });
        if (res.ok) j = await res.json(); else await sleep(2000 * (attempt + 1));
      } catch { await sleep(2000 * (attempt + 1)); }
    }
    if (!j) break;
    const back = new Map(); // final title -> asked titles
    const hop = (from, to) => { for (const [k, v] of back) if (k === from) { back.delete(k); back.set(to, v); } };
    for (const t of titles) back.set(t, [t]);
    for (const n of j.query?.normalized || []) { const v = back.get(n.from) || [n.from]; back.delete(n.from); back.set(n.to, v); }
    for (const r of j.query?.redirects || []) { const v = back.get(r.from) || [r.from]; back.delete(r.from); back.set(r.to, [...(back.get(r.to) || []), ...v]); }
    void hop;
    for (const p of j.query?.pages || []) {
      if (p.missing || p.invalid) continue;
      const sum = p.pageprops && "disambiguation" in p.pageprops ? 0 : Object.values(p.pageviews || {}).reduce((a, b) => a + (b || 0), 0);
      for (const asked of back.get(p.title) || []) out.set(asked, Math.max(out.get(asked) || 0, sum));
    }
    if (!j.continue) break;
    cont = j.continue;
    await sleep(100);
  }
  return out;
}

const median = (xs) => { const s = xs.filter((x) => x > 0).sort((a, b) => a - b); return s.length >= 3 ? s[Math.floor(s.length / 2)] : null; };

const previous = fs.existsSync(OUT) ? (await import(OUT.href + "?" + Date.now())).RARITY : {};
// judge the hand-written / generated tiers, not last run's: start from an empty rarity file
const header = "// GENERATED by tools/rescale-rarity.mjs from English Wikipedia page views. Do not edit by hand.\n// Answers that are far more famous than their tier says, moved to a more common tier: prompt -> { answer: tier }.\n";
const write = (obj) => fs.writeFileSync(OUT, header + "export const RARITY = " + JSON.stringify(obj) + ";\n");
write(only ? Object.fromEntries(Object.entries(previous).filter(([q]) => !only.has(q))) : {});
const dataFile = new URL("../public/vroomillion/js/data.js", import.meta.url);
const { QUESTIONS } = await import(dataFile.href);
const result = only ? { ...previous } : {};
let moved = 0, checked = 0;
async function rescale(q) {
  // the answers to look up, with every title spelling worth trying
  const items = [];
  q.a.forEach((list, t) => list.slice(0, PER_TIER[t]).forEach((entry) => {
    const forms = entry.split("|").slice(0, 2);
    const tries = [...new Set(forms.flatMap((f) => [firstUp(f), titleCase(f)]))];
    items.push({ tier: t + 1, key: normalize(forms[0]), display: forms[0], tries, v: 0 });
  }));
  const all = [...new Set(items.flatMap((x) => x.tries))];
  const got = new Map();
  const need = all.filter((t) => !cache.has(t));
  for (let i = 0; i < need.length; i += 50) {
    const batch = need.slice(i, i + 50);
    const res = await views(batch);
    for (const t of batch) cache.set(t, res.get(t) || 0);
    await sleep(120);
  }
  for (const t of all) got.set(t, cache.get(t) || 0);
  if (need.length) saveCache();
  for (const it of items) it.v = Math.max(0, ...it.tries.map((t) => got.get(t) || 0));
  checked += items.length;
  const m = [1, 2, 3, 4].map((t) => median(items.filter((x) => x.tier === t).map((x) => x.v)));
  if (process.env.DEBUG) { console.log("medians", m); for (const it of items) console.log(it.tier, it.v, it.display); }
  const changes = {};
  for (const it of items) {
    if (it.tier < 3 || !it.v) continue;
    // Page views say how famous a thing is, not how often people name it, so only clear mismatches move,
    // and never all the way to TRAFFIC (that tier stays hand-picked).
    let to = it.tier;
    const [m1, m2, m3] = m;
    if (it.tier === 3) { if (m1 && it.v >= 2 * m1) to = 2; }
    else if (it.tier === 4) { if (m1 && it.v >= m1) to = 2; else if (m2 && it.v >= m2) to = 3; }
    else if (it.tier === 5) {
      // Rarity means "rarely said", not "obscure": Kiribati stays a Vroomillion country. Only an answer as
      // famous as the prompt's everyday answers (Frank's RedHot for hot sauce) moves down.
      if (m1 && it.v >= m1) to = 2;
      else if (m2 && it.v >= m2) to = 3;
    }
    if (to < it.tier) { changes[it.key] = to; moved++; }
  }
  if (Object.keys(changes).length) result[q.q] = changes;
  else delete result[q.q];
  const shown = Object.entries(changes).slice(0, 6).map(([k, t]) => `${k}→${t}`).join(", ");
  console.log(`${q.q}: ${Object.keys(changes).length} moved${shown ? " (" + shown + ")" : ""}`);
}
const todo = QUESTIONS.filter((q) => !q.variant && (!only || only.has(q.q)));
const POOL = Number(process.env.POOL || 5);
let next = 0;
await Promise.all(Array.from({ length: POOL }, async () => { while (next < todo.length) await rescale(todo[next++]); }));
write(result);
console.log(`checked ${checked} answers, moved ${moved}`);
