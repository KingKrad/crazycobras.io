// CHRISTMAS: writes the Christmas prompt catalog (public/vroomillion/js/catalog/xmas.js, pool "xmas"):
// the hand-written lists (tools/xmas/lists.mjs) as families with their answer files, plus the game's own
// Christmas prompts joined in (XMAS_JOIN).   node tools/xmas/make-catalog.mjs
import fs from "node:fs";
import { FAMILIES } from "../../public/vroomillion/js/catalog/index.js";
import { answerSlug } from "../../public/vroomillion/js/racepick.js";
import { LISTS, OLD } from "./lists.mjs";

const TOPICS = ["movies", "songs", "santa", "world", "festive"];
const lines = Object.fromEntries(TOPICS.map((t) => [t, []]));
const join = { ...OLD };
const others = FAMILIES.filter((f) => !/^xmas[a-z]*\//.test(f.id));
const have = new Map(others.flatMap((f) => f.prompts.map((p) => [p.toLowerCase(), f])));
for (const id of Object.keys(OLD)) if (!others.some((f) => f.id === id)) throw new Error("no family " + id);

for (const [prompt, topic, lvl, ...tiers] of LISTS) {
  if (!TOPICS.includes(topic)) throw new Error("bad topic " + topic);
  const id = "xmas" + topic + "/" + prompt.toLowerCase().replace(/^name an? /, "").replace(/[^a-z0-9]+/g, "").slice(0, 40);
  const old = have.get(prompt.toLowerCase());
  if (old) { join[old.id] = `${topic}:${lvl}`; continue; }
  const a = [...tiers, [], [], [], []].slice(0, 5).map((t) => [...t]);
  const top = a[0].map((e) => e.split("|")[0]);
  if (top.some((t) => /[,|]/.test(t)) || top.length < 5) throw new Error("bad list for " + prompt);
  lines[topic].push(`${id} | ${lvl} | xmas | g:${topic} | ${prompt} | | ${top.join(", ")}`);
  const file = new URL(`../../public/vroomillion/answers/${answerSlug(prompt)}.json`, import.meta.url);
  if (fs.existsSync(file) && JSON.parse(fs.readFileSync(file, "utf8")).fam !== id) throw new Error(`${prompt}: answers/ already has this prompt for another family`);
  fs.writeFileSync(file, JSON.stringify({ q: prompt, a, tiers: [999999, 999999], fam: id, hand: true }));
}

let out = `// GENERATED by tools/xmas/make-catalog.mjs: the CHRISTMAS mode's own prompts (pool "xmas"); answers in
// public/vroomillion/answers (written by the same tool, from tools/xmas/lists.mjs).
export const XMAS = \`
`;
// each section's topic in the rest of the game (the catalog's own topics)
const GAME_TOPIC = { movies: "screen", songs: "music", santa: "people", world: "places", festive: "wild" };
for (const [topic, ls] of Object.entries(lines)) out += `# ${GAME_TOPIC[topic]}\n// ${topic}\n` + ls.join("\n") + "\n";
out += "`;\n\n// the game's own Christmas prompts that CHRISTMAS plays too: family id -> \"topic:level\"\nexport const XMAS_JOIN = " + JSON.stringify(join, null, 1) + ";\n";
fs.writeFileSync(new URL("../../public/vroomillion/js/catalog/xmas.js", import.meta.url), out);
const all = [...Object.values(lines).flat().map((l) => l.split("|")[1].trim()), ...Object.values(join).map((v) => v.split(":")[1])];
console.log("CHRISTMAS: new", Object.values(lines).flat().length, "| joined", Object.keys(join).length, "| easy", all.filter((l) => l === "1").length, "| total", all.length);
