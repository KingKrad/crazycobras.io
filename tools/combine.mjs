// Combines answer sources: the game's actor and director prompts ("Name a Tom Hanks movie", "Name a Matt
// Damon or Ben Affleck movie", "Name a Steven Spielberg film") get every film in that person's Wikidata
// filmography as an accepted answer, so a famous film missing from the hand-written list still counts.
// The filmographies were built for BOX OFFICE (tools/film/make-catalog.mjs) and are kept in the git history;
// this reads them from there and writes public/vroomillion/js/data-combined.js (used by data.js, after the
// hand-written tiers, which always win).   node tools/combine.mjs
import fs from "node:fs";
import { execFileSync } from "node:child_process";

const ROOT = new URL("..", import.meta.url).pathname;
const git = (...a) => execFileSync("git", a, { cwd: ROOT, maxBuffer: 256 << 20 }).toString();
// the commits that hold the filmographies: the newer one first (its lists include voice roles)
const COMMITS = ["c2c874a", "f54c958"];
const BAD = /(\bdrugs?\b|\bsexy?\b|\bwhores?\b|pussycat|\bporn|f\*+ing|b----|\bcocaine\b|\bheroin\b|\bstripper|\berotic|\bnude\b|\bnaked\b| in film$|filmography|\(film series\))/i;
const norm = (s) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, " ").trim();

const lists = new Map(); // person -> [tier lists]
for (const c of COMMITS) {
  for (const f of git("ls-tree", "-r", "--name-only", c, "public/vroomillion/answers").split("\n")) {
    const m = f.match(/answers\/name-a-(?:movie-starring|film-directed-by)-(.+)\.json$/);
    if (!m) continue;
    let d;
    try { d = JSON.parse(git("show", `${c}:${f}`)); } catch { continue; }
    const who = norm(String(d.q || "").replace(/^Name a (movie starring|film directed by) /, ""));
    if (!who || lists.has(who)) continue; // the newer commit's list wins
    lists.set(who, d.a.map((t) => t.filter((e) => !BAD.test(e))));
  }
}

// every prompt in the game that names people's films
const { QUESTIONS } = await import(ROOT + "public/vroomillion/js/data.js");
const { FAMILIES } = await import(ROOT + "public/vroomillion/js/catalog/index.js");
const prompts = new Set([...QUESTIONS.map((q) => q.q), ...FAMILIES.flatMap((f) => f.prompts)]);
const out = {};
let matched = 0, people = 0;
for (const p of prompts) {
  const m = p.match(/^Name an? (.+?) (?:movie|film)s?(?: or show)?$/i);
  if (!m) continue;
  const names = m[1].split(/,\s*|\s+or\s+|\s+and\s+|\s*&\s*/).map(norm).filter(Boolean);
  const found = names.map((n) => lists.get(n)).filter(Boolean);
  if (!found.length) continue;
  matched++; people += found.length;
  // their filmography's tiers -> this prompt's [CRUISING, FAST LANE, DEEP CUT]
  const tiers = [[], [], []];
  for (const a of found) {
    tiers[0].push(...(a[0] || []), ...(a[1] || []));
    tiers[1].push(...(a[2] || []));
    tiers[2].push(...(a[3] || []), ...(a[4] || []));
  }
  out[p] = tiers.map((t) => [...new Set(t)]);
}
const text = `// GENERATED by tools/combine.mjs: films from the Wikidata filmographies of the people in the game's actor
// and director prompts, as extra accepted answers [CRUISING, FAST LANE, DEEP CUT]. Hand-written tiers win.
export const COMBINED = ${JSON.stringify(out)};
`;
fs.writeFileSync(ROOT + "public/vroomillion/js/data-combined.js", text);
console.log(`filmographies: ${lists.size} people | prompts given them: ${matched} (${people} people) | ${Math.round(text.length / 1024)} KB`);
