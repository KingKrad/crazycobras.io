// STADIUM RUN: writes the sports prompt catalog (public/vroomillion/js/catalog/sport.js, pool "sport").
// Most of it is the game's own hand-written sports prompts (athletes, teams, terms, gear...), joined into
// the "sport" pool with a STADIUM RUN topic and level (SPORT_JOIN). New hand-written lists fill the gaps
// (F1, WWE, Olympians, the Premier League...); their answer files are written here.
//   node tools/sport/make-catalog.mjs
import fs from "node:fs";
import { FAMILIES } from "../../public/vroomillion/js/catalog/index.js";
import { answerSlug } from "../../public/vroomillion/js/racepick.js";
import { LISTS } from "./lists.mjs";

const TOPICS = ["athletes", "teams", "events", "terms", "gear", "gameday"];
const lines = Object.fromEntries(TOPICS.map((t) => [t, []]));
const join = {};
const others = FAMILIES.filter((f) => !f.id.startsWith("spo/") && !f.pools.includes("car")); // car prompts stay in CAR MODE // (joined families already list "sport" from the last run)
const have = new Map(others.flatMap((f) => f.prompts.map((p) => [p.toLowerCase(), f])));

for (const [prompt, topic, lvl, ...tiers] of LISTS) {
  const id = "spo/" + prompt.toLowerCase().replace(/^name an? /, "").replace(/[^a-z0-9]+/g, "").slice(0, 24);
  const old = have.get(prompt.toLowerCase());
  if (old) { join[old.id] = `${topic}:${lvl}`; continue; }
  const a = [...tiers, [], [], [], []].slice(0, 5).map((t) => [...t]);
  const top = a[0].map((e) => e.split("|")[0]);
  if (top.some((t) => /[,|]/.test(t)) || top.length < 4) throw new Error("bad list for " + prompt);
  lines[topic].push(`${id} | ${lvl} | sport | g:${topic} | ${prompt} | | ${top.join(", ")}`);
  const file = new URL(`../../public/vroomillion/answers/${answerSlug(prompt)}.json`, import.meta.url);
  // never over another family's answers (a prompt another mode already has)
  if (fs.existsSync(file) && JSON.parse(fs.readFileSync(file, "utf8")).fam !== id) throw new Error(`${prompt}: answers/ already has this prompt for another family`);
  fs.writeFileSync(file, JSON.stringify({ q: prompt, a, tiers: [999999, 999999], fam: id, hand: true }));
}

// the game's own sports prompts
const SPORTY = /\b(sports?|athletes?|players?|team|club|league|olympic|olympics|nfl|nba|mlb|nhl|mls|soccer|football|baseball|basketball|hockey|tennis|golf|golfer|boxer|boxing|swimmer|cricketer|quarterback|stadium|referee|coach|mascot|marathon|wrestling|gymnastics|racehorse|skateboard\w*|surf(ing|er|ers|board\w*)?|ski(ing|er|ers|s)?|bowling|fishing)\b/i;
for (const f of others) {
  const p = f.prompts[0];
  if (f.pools.includes("car")) continue;
  if (!(f.topic === "sports" || SPORTY.test(p))) continue;
  if (/(character|cartoon|movie|film|TV show|video game|song|band|card game|board game|cereal)/i.test(p)) continue;
  let topic;
  if (/\b(player|athlete|golfer|boxer|swimmer|cricketer|quarterback|legend|coach|GOAT|medalist|skateboarder|surfer|snowboarder|nickname|mascot|wrestler)\b/i.test(p)) topic = "athletes";
  else if (/\b(team|club|college)\b/i.test(p)) topic = "teams";
  else if (/\b(term|move|position|stroke|word|injury)\b/i.test(p)) topic = "terms";
  else if (/need to play|equipment|wears?|ball used|bag|locker|trophy|stadium|use or|swimmers wear/i.test(p)) topic = "gear";
  else if (/^Name (something|a reason)/i.test(p)) topic = "gameday";
  else topic = "events";
  let lvl = Math.min(f.level, 2);
  if (/starts? with|begins? with/i.test(p)) lvl = 2;
  if (f.level >= 3) lvl = 3;
  join[f.id] = `${topic}:${lvl}`;
}

let out = `// GENERATED by tools/sport/make-catalog.mjs: STADIUM RUN's own sports prompts (pool "sport"); answers in
// public/vroomillion/answers (written by the same tool, from tools/sport/lists.mjs).
export const SPORT = \`
`;
for (const [topic, ls] of Object.entries(lines)) out += `# sports\n// ${topic}\n` + ls.join("\n") + "\n";
out += "`;\n\n// the game's own sports prompts that STADIUM RUN plays too: family id -> \"topic:level\" there\nexport const SPORT_JOIN = " + JSON.stringify(join, null, 1) + ";\n";
fs.writeFileSync(new URL("../../public/vroomillion/js/catalog/sport.js", import.meta.url), out);
const count = (k) => Object.values(join).filter((v) => v.startsWith(k + ":")).length;
console.log("STADIUM RUN: new", Object.values(lines).reduce((a, l) => a + l.length, 0), "| joined", Object.keys(join).length, TOPICS.map((t) => `${t} ${lines[t].length + count(t)}`).join(", "));
