// ON TOUR: writes the music prompt catalog (public/vroomillion/js/catalog/music.js, pool "music").
// Most of ON TOUR is the game's own hand-written music prompts (songs by artist, decades, instruments,
// festivals...), joined into the "music" pool with an ON TOUR topic and level (MUSIC_JOIN). New
// hand-written lists fill the gaps (boy bands, K-pop, instruments by family, albums); their answer files
// are written here.   node tools/music/make-catalog.mjs
import fs from "node:fs";
import { FAMILIES } from "../../public/vroomillion/js/catalog/index.js";
import { answerSlug } from "../../public/vroomillion/js/racepick.js";
import { LISTS } from "./lists.mjs";

const TOPICS = ["songs", "themes", "artists", "albums", "eras", "instruments", "stage"];
const lines = Object.fromEntries(TOPICS.map((t) => [t, []]));
const join = {};
const others = FAMILIES.filter((f) => !f.id.startsWith("mus/")); // (joined families already list "music" from the last run)
const have = new Map(others.flatMap((f) => f.prompts.map((p) => [p.toLowerCase(), f])));

// the hand-written lists: a family each (or, if the game already asks it, that family joins)
for (const [prompt, topic, lvl, ...tiers] of LISTS) {
  const id = "mus/" + prompt.toLowerCase().replace(/^name an? /, "").replace(/[^a-z0-9]+/g, "").slice(0, 24);
  const old = have.get(prompt.toLowerCase());
  if (old) { join[old.id] = `${topic}:${lvl}`; continue; }
  const a = [...tiers, [], [], [], []].slice(0, 5).map((t) => [...t]);
  const top = a[0].map((e) => e.split("|")[0]);
  if (top.some((t) => /[,|]/.test(t)) || top.length < 5) throw new Error("bad list for " + prompt);
  lines[topic].push(`${id} | ${lvl} | music | g:${topic} | ${prompt} | | ${top.join(", ")}`);
  fs.writeFileSync(new URL(`../../public/vroomillion/answers/${answerSlug(prompt)}.json`, import.meta.url), JSON.stringify({ q: prompt, a, tiers: [999999, 999999], fam: id, hand: true }));
}

// the game's own music prompts
const MUSICAL = /\b(songs?|albums?|band|singers?|rappers?|DJ|composer|music|musical|opera|karaoke|guitarist|drummer|piano player|instruments?)\b/i;
const FAMOUS = /^(Taylor Swift|Beatles|The Beatles|Queen|Michael Jackson|Elvis Presley|Elvis|Madonna|Beyoncé|Beyonce|Ed Sheeran|Ariana Grande|Billie Eilish|Drake|Eminem|Rihanna|Lady Gaga|Katy Perry|Justin Bieber|Bruno Mars|Adele|The Weeknd|BTS|Harry Styles|One Direction|Dua Lipa|Olivia Rodrigo|Sabrina Carpenter|Coldplay|Imagine Dragons|ABBA|Elton John|Bon Jovi|Whitney Houston|Mariah Carey|Britney Spears|Disney|Maroon 5|Post Malone|Miley Cyrus|Selena Gomez|Shakira|Bob Marley|Stevie Wonder|Nirvana|AC\/DC|Linkin Park|Green Day|Backstreet Boys|Frank Sinatra|Dolly Parton|Kanye West|Travis Scott|Lizzo|Doja Cat|Bad Bunny)$/i;
for (const f of others) {
  const p = f.prompts[0];
  if (f.pools.includes("car")) continue;
  if (!(f.topic === "music" || MUSICAL.test(p))) continue;
  if (/(character|cartoon|rhymes|TV show|\bshow\b)/i.test(p) || (/\b(movie|film)\b/i.test(p) && !/\bsongs?\b/i.test(p))) continue;
  if (/^Name something\b/i.test(p)) continue; // "something at a music store": not really about music
  let topic, lvl = Math.min(f.level, 2);
  const artist = (p.match(/^Name an? (.+?) songs?$/) || p.match(/^Name a song by (.+)$/) || [])[1];
  if (/album/i.test(p)) topic = "albums";
  else if (/instrument|guitarist|drummer|piano player|guitar riff/i.test(p)) topic = "instruments";
  else if (/festival|composer|musical|opera/i.test(p)) topic = "stage";
  else if (/'[0-9]0s|\b(19|20)[0-9]0s\b|genre/i.test(p)) topic = "eras";
  else if (artist && /^[A-Z0-9'"]/.test(artist)) {
    topic = "songs";
    lvl = !/,| or | and |&/.test(artist) && (FAMOUS.test(artist) || f.level === 1) ? 1 : 2;
  } else if (/\bsongs?\b|duet|karaoke/i.test(p)) topic = "themes";
  else topic = "artists";
  if (topic === "eras" && /^Name an? song from the/i.test(p)) lvl = 1; // "a song from the '90s": everyone has one
  if (/starts? with|begins? with/i.test(p)) lvl = 2; // letter games aren't for the easy track
  if (f.level >= 3) lvl = 3;
  join[f.id] = `${topic}:${lvl}`;
}

let out = `// GENERATED by tools/music/make-catalog.mjs: ON TOUR's own music prompts (pool "music"); answers in
// public/vroomillion/answers (written by the same tool, from tools/music/lists.mjs).
export const MUSIC = \`
`;
for (const [topic, ls] of Object.entries(lines)) out += `# music\n// ${topic}\n` + ls.join("\n") + "\n";
out += "`;\n\n// the game's own music prompts that ON TOUR plays too: family id -> \"topic:level\" in ON TOUR\nexport const MUSIC_JOIN = " + JSON.stringify(join, null, 1) + ";\n";
fs.writeFileSync(new URL("../../public/vroomillion/js/catalog/music.js", import.meta.url), out);
const count = (k) => Object.values(join).filter((v) => v.startsWith(k + ":")).length;
console.log("ON TOUR: new", Object.values(lines).reduce((a, l) => a + l.length, 0), "| joined", Object.keys(join).length, TOPICS.map((t) => `${t} ${lines[t].length + count(t)}`).join(", "),
  "| easy", Object.values(join).filter((v) => v.endsWith(":1")).length + LISTS.filter((l) => l[2] === 1).length);
