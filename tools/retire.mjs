// Writes public/vroomillion/js/catalog/retired.js: the prompt families Unlimited races no longer use,
// because nothing but a short hand-written list can check their answers (there's no AI judge).
// A family stays in play if any of its prompts has:
//   - a Wikidata rule (src/answer-classes.js, src/catalog-classes.js) or a Wikidata long tail (deep/)
//   - dictionary answers (tools/build-words.py)
//   - a complete list built from data (an answers file that isn't hand-written, a merged filmography
//     ("expanded"), a map trivia list ("at")), or answers in the original game data (no answers file)
// The daily races and CHRISTMAS (a limited-time mode) are never affected.
//   node tools/retire.mjs           (run after building answers or adding prompts)
import fs from "node:fs";
import { FAMILIES } from "../public/vroomillion/js/catalog/index.js";
import { answerSlug } from "../public/vroomillion/js/racepick.js";
import { CLASSES } from "../src/answer-classes.js";
import { CATALOG_CLASSES } from "../src/catalog-classes.js";

const deep = JSON.parse(fs.readFileSync(new URL("../public/vroomillion/deep/index.json", import.meta.url), "utf8"));
const checkable = (p) => {
  if (CLASSES[p] || CATALOG_CLASSES[p] || deep[p]) return true;
  const file = new URL(`../public/vroomillion/answers/${answerSlug(p)}.json`, import.meta.url);
  if (!fs.existsSync(file)) return true;
  const d = JSON.parse(fs.readFileSync(file, "utf8"));
  return !d.hand || !!(d.dict || d.live || d.expanded || d.at);
};
const retired = FAMILIES.filter((f) => !f.prompts.some(checkable)).map((f) => f.id).sort();
fs.writeFileSync(new URL("../public/vroomillion/js/catalog/retired.js", import.meta.url), `// GENERATED by tools/retire.mjs. Do not edit by hand.
// Families Unlimited races skip: their answers can only be checked against a short hand-written list.
// (The daily races and CHRISTMAS still use them.)
export const RETIRED = new Set(${JSON.stringify(retired)});
`);
const pools = {};
for (const f of FAMILIES) for (const p of f.pools) { pools[p] ||= [0, 0]; pools[p][retired.includes(f.id) ? 1 : 0]++; }
console.log(`${retired.length} of ${FAMILIES.length} families retired from Unlimited`);
for (const [p, [keep, gone]] of Object.entries(pools)) console.log(`  ${p}: ${keep} in play, ${gone} retired${p === "daily" || p === "xmas" ? " (not applied)" : ""}`);
