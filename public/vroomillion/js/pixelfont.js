export const GLYPH_H = 7;

const glyph = (ch) => G[ch] || G[ch.toUpperCase()] || G["?"];

// width in font pixels (before scaling), with one pixel between letters
export function textWidth(text, gap = 1) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + gap;
  return Math.max(0, w - gap);
}

// A canvas holding the text at `scale`x, with a dark drop shadow one font pixel down and right.
export function fontLine(text, scale, colour, shadow = "#05020c") {
  const s = Math.max(1, Math.round(scale));
  const gap = 1;
  const cv = document.createElement("canvas");
  cv.width = Math.max(1, (textWidth(text, gap) + 1) * s);
  cv.height = (GLYPH_H + 1) * s;
  const g = cv.getContext("2d");
  const paint = (col, ox, oy) => {
    g.fillStyle = col;
    let x = 0;
    for (const ch of text) {
      const rows = glyph(ch);
      rows.forEach((row, ry) => {
        for (let rx = 0; rx < row.length; rx++) if (row[rx] === "1") g.fillRect((x + rx + ox) * s, (ry + oy) * s, s, s);
      });
      x += rows[0].length + gap;
    }
  };
  if (shadow) paint(shadow, 1, 1);
  paint(colour, 0, 0);
  return cv;
}
